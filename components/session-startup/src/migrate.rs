//! `tessel-migrate`: move a desktop-suite (pre-Tessel) home to Tessel's layout once,
//! at the start of the first Tessel login (docs/LAYOUT.md, "Migration").
//!
//! Old files and directories are copied, never moved or deleted, and an existing new
//! path always wins. Copied text files, `~/.config/labwc/rc.xml` and
//! `~/.config/mimeapps.list` get the old program names and ids replaced. Units the
//! user enabled under their old names are enabled under the new ones. A marker file
//! makes every later run a no-op.

use std::fs;
use std::io;
use std::os::unix::fs::{symlink, PermissionsExt};
use std::path::{Path, PathBuf};

/// `~/.config/tessel/.migrated`: present once the migration ran.
pub const MARKER: &str = ".migrated";

/// The XDG base directories a migration works in (tests use a fake home).
#[derive(Clone, Debug)]
pub struct Home {
    pub config: PathBuf,
    pub data: PathBuf,
    pub state: PathBuf,
    pub cache: PathBuf,
}

impl Home {
    pub fn current() -> Self {
        use tessel_core::paths;
        Self { config: paths::config_home(), data: paths::data_home(), state: paths::state_home(), cache: paths::cache_home() }
    }

    /// `$HOME`-relative layout under `root` (tests).
    pub fn under(root: &Path) -> Self {
        Self { config: root.join(".config"), data: root.join(".local/share"), state: root.join(".local/state"),
               cache: root.join(".cache") }
    }
}

#[derive(Clone, Copy)]
enum Base {
    Config,
    Data,
    State,
    Cache,
}

