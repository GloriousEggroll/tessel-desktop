/// Units the user may have enabled under their old names: (old, new).
pub const ENABLED_UNITS: &[(&str, &str)] = &[
    ("clipboard-manager.service", "tessel-clipboard.service"),
    ("night-light.service", "tessel-night-light.service"),
];

/// Text files larger than this are copied without rewriting.
const REWRITE_LIMIT: u64 = 4 * 1024 * 1024;

#[derive(Debug, Default, PartialEq, Eq)]
pub struct Report {
    /// New paths created from old ones.
    pub copied: Vec<PathBuf>,
    /// Files whose old names were replaced.
    pub rewritten: Vec<PathBuf>,
    /// (old, new) units to switch: disable the old, enable the new.
    pub units: Vec<(String, String)>,
    /// Whether this run did anything (false once the marker exists).
    pub ran: bool,
}

fn base(home: &Home, base: Base) -> &Path {
    match base {
        Base::Config => &home.config,
        Base::Data => &home.data,
        Base::State => &home.state,
        Base::Cache => &home.cache,
    }
}

/// `text` with every old name replaced; `None` when nothing changed.
pub fn replace_names(text: &str) -> Option<String> {
    let mut out = text.to_owned();
    for (old, new) in REPLACEMENTS {
        if out.contains(old) {
            out = out.replace(old, new);
        }
    }
    (out != text).then_some(out)
}

fn rewrite_file(path: &Path, report: &mut Report) -> io::Result<()> {
    let meta = fs::symlink_metadata(path)?;
    if !meta.is_file() || meta.len() > REWRITE_LIMIT {
        return Ok(());
    }
    let Ok(text) = String::from_utf8(fs::read(path)?) else { return Ok(()) };
    if let Some(new) = replace_names(&text) {
        write_keeping_mode(path, new.as_bytes(), meta.permissions().mode())?;
        report.rewritten.push(path.to_owned());
    }
    Ok(())
}

/// Temporary file beside `path`, then rename: an interrupted run never leaves half a file.
fn write_keeping_mode(path: &Path, data: &[u8], mode: u32) -> io::Result<()> {
    let name = path.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let temporary = path.with_file_name(format!(".{name}.tessel-migrate"));
    fs::write(&temporary, data)?;
    fs::set_permissions(&temporary, fs::Permissions::from_mode(mode & 0o7777))?;
    fs::rename(&temporary, path)
}

/// Copy `from` to `to` (files, directories, symlinks as symlinks), rewriting text.
fn copy_tree(from: &Path, to: &Path, report: &mut Report) -> io::Result<()> {
    let meta = fs::symlink_metadata(from)?;
    if meta.file_type().is_symlink() {
        symlink(fs::read_link(from)?, to)?;
    } else if meta.is_dir() {
        fs::create_dir_all(to)?;
        fs::set_permissions(to, fs::Permissions::from_mode(meta.permissions().mode() & 0o7777))?;
        let mut entries: Vec<_> = fs::read_dir(from)?.filter_map(Result::ok).collect();
        entries.sort_by_key(|entry| entry.file_name());
        for entry in entries {
            let target = to.join(entry.file_name());
            if fs::symlink_metadata(&target).is_err() {
                copy_tree(&entry.path(), &target, report)?;
            }
        }
    } else if meta.is_file() {
        fs::copy(from, to)?;
        fs::set_permissions(to, fs::Permissions::from_mode(meta.permissions().mode() & 0o7777))?;
        rewrite_file(to, report)?;
    }
    Ok(())
}

/// Copy the old paths that exist and whose new path does not, then rewrite the
/// labwc and mime configuration. Never deletes anything. Idempotent.
pub fn migrate(home: &Home) -> io::Result<Report> {
    let marker = home.config.join("tessel").join(MARKER);
    let mut report = Report::default();
    if marker.exists() {
        return Ok(report);
    }
    report.ran = true;
    for (kind, old, new) in PATHS {
        let root = base(home, *kind);
        let (from, to) = (root.join(old), root.join(new));
        if fs::symlink_metadata(&from).is_err() {
            continue;
        }
        let existed = fs::symlink_metadata(&to).is_ok();
        if existed && !to.is_dir() {
            continue;
        }
        if let Some(parent) = to.parent() {
            fs::create_dir_all(parent)?;
        }
        // An existing new directory (a shared one copied above) gains only what it lacks.
        copy_tree(&from, &to, &mut report)?;
        if !existed {
            report.copied.push(to);
        }
    }
    for file in [home.config.join("labwc/rc.xml"), home.config.join("labwc/menu.xml"), home.config.join("mimeapps.list"),
                 home.data.join("applications/mimeapps.list")] {
        if file.is_file() {
            rewrite_file(&file, &mut report)?;
        }
    }
    let wants = home.config.join("systemd/user/graphical-session.target.wants");
    for (old, new) in ENABLED_UNITS {
        if fs::symlink_metadata(wants.join(old)).is_ok() && fs::symlink_metadata(wants.join(new)).is_err() {
            report.units.push(((*old).to_owned(), (*new).to_owned()));
        }
    }
    fs::create_dir_all(marker.parent().unwrap())?;
    fs::write(&marker, "1\n")?;
    Ok(report)
}

/// `tessel-migrate`: run the migration, switch enabled units, reload labwc when its
/// configuration changed. Quiet unless something happened; always exits 0 so a
/// login never stops here.
pub fn main() -> i32 {
    let report = match migrate(&Home::current()) {
        Ok(report) => report,
        Err(error) => {
            eprintln!("tessel-migrate: {error}");
            return 0;
        }
    };
    if !report.ran {
        return 0;
    }
    for path in &report.copied {
        println!("tessel-migrate: created {}", path.display());
    }
    for (old, new) in &report.units {
        let status = std::process::Command::new("systemctl").args(["--user", "enable", new]).status();
        if status.is_ok_and(|s| s.success()) {
            let _ = std::process::Command::new("systemctl").args(["--user", "disable", old]).status();
            println!("tessel-migrate: {old} is now {new}");
        }
    }
    let labwc_changed = report.rewritten.iter().any(|p| p.ends_with("labwc/rc.xml") || p.ends_with("labwc/menu.xml"));
    if labwc_changed && std::env::var_os("LABWC_PID").is_some_and(|pid| !pid.is_empty()) {
        let _ = std::process::Command::new("labwc").arg("--reconfigure").status();
    }
    0
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp() -> PathBuf {
        // Inside the workspace's target/ (unit tests must not depend on TMPDIR).
        let name = format!("migrate-test-{}-{:?}", std::process::id(), std::thread::current().id()).replace(['(', ')'], "");
        let dir = Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../target/test-tmp")).join(name);
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn write(path: &Path, text: &str) {
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, text).unwrap();
    }

    #[test]
    fn copies_old_settings_rewrites_names_and_runs_once() {
        let root = temp();
        let home = Home::under(&root);
        write(&root.join(".config/waydock/config.json"), r#"{"pins": ["org.waydock.Files.desktop", "helium.desktop"]}"#);
        write(&root.join(".config/desktop-suite/clock.json"), "{}");
        write(&root.join(".config/waybar/network-notifications.json"), "[]");
        write(&root.join(".local/share/desktop-suite/keyring/master.json"), "{}");
        fs::set_permissions(root.join(".local/share/desktop-suite/keyring/master.json"), fs::Permissions::from_mode(0o600)).unwrap();
        write(&root.join(".config/labwc/rc.xml"),
              r#"<keybind key="W-l"><action name="Execute" command="~/.local/bin/wayshell-lock"/></keybind>
<keybind key="Print"><action name="Execute"><command>/usr/local/bin/waycapture --capture screen</command></action></keybind>
<keybind key="A-Tab"><action name="Execute" command="~/.local/share/wayshell/wayshell-cli switch-window"/></keybind>"#);
        write(&root.join(".config/mimeapps.list"), "[Default Applications]\ninode/directory=org.waydock.Files.desktop;\n");
        write(&root.join(".config/systemd/user/graphical-session.target.wants/clipboard-manager.service"), "");
        // A new file that already exists wins over the old one.
        write(&root.join(".config/tessel/language.json"), "new");
        write(&root.join(".config/desktop-suite/language.json"), "old");

        let report = migrate(&home).unwrap();
        assert!(report.ran);
        let read = |p: &str| fs::read_to_string(root.join(p)).unwrap();
        assert_eq!(read(".config/tessel/dock/config.json"), r#"{"pins": ["org.tessel.Files.desktop", "helium.desktop"]}"#);
        assert_eq!(read(".config/tessel/clock.json"), "{}");
        assert_eq!(read(".config/tessel/language.json"), "new");
        assert_eq!(read(".config/tessel/network/notifications.json"), "[]");
        assert_eq!(fs::metadata(root.join(".local/share/tessel/keyring/master.json")).unwrap().permissions().mode() & 0o777, 0o600);
        let rc = read(".config/labwc/rc.xml");
        assert!(rc.contains(r#"command="~/.local/bin/tessel-shell-lock""#), "{rc}");
        assert!(rc.contains("/usr/local/bin/tessel-capture --capture screen"), "{rc}");
        assert!(rc.contains("~/.local/bin/tessel-shell-cli switch-window"), "{rc}");
        assert_eq!(read(".config/mimeapps.list"), "[Default Applications]\ninode/directory=org.tessel.Files.desktop;\n");
        assert_eq!(report.units, vec![("clipboard-manager.service".to_owned(), "tessel-clipboard.service".to_owned())]);
        // Old files stay.
        assert!(root.join(".config/waydock/config.json").exists());

        // The second run is a no-op even if old files change.
        write(&root.join(".config/waydock/config.json"), "changed");
        assert_eq!(migrate(&home).unwrap(), Report::default());
        assert_ne!(read(".config/tessel/dock/config.json"), "changed");
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn nothing_old_means_only_the_marker() {
        let root = temp();
        let report = migrate(&Home::under(&root)).unwrap();
        assert!(report.ran && report.copied.is_empty() && report.rewritten.is_empty());
        assert!(root.join(".config/tessel").join(MARKER).exists());
        fs::remove_dir_all(root).unwrap();
    }

    #[test]
    fn specific_ids_are_replaced_before_their_namespace() {
        assert_eq!(replace_names("org.waydock.Waydock org.waybar.PowerManager.desktop waydock.desktop").unwrap(),
                   "org.tessel.Dock org.tessel.PowerManager.desktop org.tessel.DockSettings.desktop");
        assert_eq!(replace_names("nothing here"), None);
    }
}
